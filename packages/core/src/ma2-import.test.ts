import { describe, expect, it } from 'vitest';
import { createEmptyLinkProject, createLightingDocument, parseLinkProject, type Ma2TimecodePreview } from '@tb/schema';
import { applyMa2ReadbackCommand, importMa2TimecodeCommand } from './ma2-import';
import { LightingTempoMap, lightingEventTime } from './lighting-edit';
import { snapshotMa2LightingBinding } from './ma2-lighting-snapshot';
import { previewMa2Sync, resolveMa2Sync } from './ma2-sync';
import { previewMa2BoundSync } from './ma2-bound-sync';

function preview(): Ma2TimecodePreview {
  const document = createLightingDocument();
  document.tracks.push({ id: 'ma-track', kind: 'ma2', name: '测试序列', color: '#ba8fff', group: '', muted: false, solo: false, locked: false, channel: 1, portProfileId: '', controller: 7, noteNames: {}, clips: [{ id: 'ma-clip', name: 'MA2', start: 0, duration: 2000, timeLock: 'time', muted: false, events: [{ id: 'ma-event', kind: 'ma2', at: 1500, sequence: 9901, cue: '7.500', executor: '99.219', label: 'Cue 7.5', action: 'goto' }] }] });
  return { target: 9902, name: '验收', readAt: '2026-09-11T00:00:00.000Z', document, sourceXml: '<MA><Timecode index="9901" /></MA>', mappings: [{ eventId: 'ma-event', trackId: 'ma-track', clipId: 'ma-clip', path: 'Timecode:9901/Track:0/SubTrack:0/Event:1', sequence: 9901, cueIndex: 2, executor: '99.219' }], warnings: [], unconverted: [] };
}
function project() {
  const value = createEmptyLinkProject('MA2 导入');
  value.rundown.push({ id: 'item', title: '节目', enabled: true, notes: '保留备注', cues: [], visualLayers: [], referenceMediaClips: [] });
  return value;
}
describe('MA2 预览应用命令', () => {
  it('控台回读的轨道顺序应用到绑定位置，未绑定轨道保持原位置', () => {
    const source = preview();
    source.document.tracks.push({ ...structuredClone(source.document.tracks[0]!), id: 'second-track', name: '第二轨', clips: [] });
    const before = importMa2TimecodeCommand('item', source).execute(project());
    const document = before.rundown[0]!.lighting!;
    document.tracks.splice(1, 0, { ...structuredClone(document.tracks[0]!), id: 'unbound', name: '本地轨道', clips: [] });
    const remote = structuredClone(source); remote.document.tracks.reverse();
    const command = applyMa2ReadbackCommand('item', document.ma2Bindings![0]!.id, document, remote);
    const next = command.execute(before);
    expect(next.rundown[0]!.lighting!.tracks.map((track) => track.id)).toEqual(['second-track', 'unbound', 'ma-track']);
    expect(next.rundown[0]!.lighting!.ma2Bindings![0]!.baselineTracks.map((track) => track.id)).toEqual(['second-track', 'ma-track']);
    expect(command.undo(before)).toEqual(before);
    expect(parseLinkProject(JSON.parse(JSON.stringify(next)))).toEqual(next);
  });
  it('真实 Cue 列表随工程保存，清空轨道仍保留已读取的打点列表', () => {
    const imported = preview();
    imported.cueCatalog = [{ sequence: 9901, name: '测试序列', cues: [{ index: 1, number: '1.250', name: null }, { index: 2, number: '7.500', name: '副歌' }] }];
    const before = parseLinkProject(JSON.parse(JSON.stringify(importMa2TimecodeCommand('item', imported).execute(project()))));
    const document = before.rundown[0]!.lighting!;
    const binding = document.ma2Bindings![0]!;
    expect(binding.cueCatalog).toEqual(imported.cueCatalog);
    const cleared = preview(); cleared.document.tracks[0]!.clips[0]!.events = []; cleared.mappings = []; cleared.cueCatalog = [];
    const command = applyMa2ReadbackCommand('item', binding.id, document, cleared);
    const next = parseLinkProject(JSON.parse(JSON.stringify(command.execute(before))));
    expect(next.rundown[0]!.lighting!.ma2Bindings![0]!.cueCatalog).toEqual(imported.cueCatalog);
    expect(command.undo(before)).toEqual(before);
  });
  it('本地标注与控台名称独立，回读、保存和撤销保留标注', () => {
    for (const annotated of [false, true]) {
      const before = importMa2TimecodeCommand('item', preview()).execute(project());
      const document = before.rundown[0]!.lighting!;
      const binding = document.ma2Bindings![0]!;
      const event = document.tracks[0]!.clips[0]!.events[0]!;
      if (event.kind !== 'ma2') throw new Error('样例类型错误');
      if (annotated) event.label = '副歌第一拍';
      const snapshots = snapshotMa2LightingBinding(document, binding.id, { consoleVersion: '3.3.4.3', baselineRevision: 'base', localRevision: 'local' });
      expect(snapshots.local.objects).toEqual(snapshots.base.objects);
      const confirmed = preview();
      const remote = confirmed.document.tracks[0]!.clips[0]!.events[0]!;
      if (remote.kind !== 'ma2') throw new Error('样例类型错误');
      remote.label = '控台改名';
      const command = applyMa2ReadbackCommand('item', binding.id, document, confirmed);
      const next = parseLinkProject(JSON.parse(JSON.stringify(command.execute(before))));
      expect(next.rundown[0]!.lighting!.tracks[0]!.clips[0]!.events[0]).toMatchObject({ label: annotated ? '副歌第一拍' : '控台改名' });
      expect(next.rundown[0]!.lighting!.ma2Bindings![0]!.baselineTracks[0]!.clips[0]!.events[0]).toMatchObject({ label: '控台改名' });
      expect(command.undo(before)).toEqual(before);
    }
  });
  it.each([false, true])('主推杆回读更新数值和位置，保留本地标注=%s，重复同步和重开不丢失', (annotated) => {
    const source = preview();
    source.document.tracks[0]!.clips[0]!.events = [{ id: 'ma-event', kind: 'ma2-fader', at: 1500, executor: '99.219', fader: 'Master', level: 0.25, label: '主推杆' }];
    source.mappings[0] = { ...source.mappings[0]!, path: 'Timecode:9901/Track:0/SubTrack:1/Event:0', sequence: null, cueIndex: null, action: 'master' };
    const before = importMa2TimecodeCommand('item', source).execute(project());
    const document = before.rundown[0]!.lighting!;
    const bindingId = document.ma2Bindings![0]!.id;
    const local = document.tracks[0]!.clips[0]!.events[0]!;
    if (local.kind !== 'ma2-fader') throw new Error('推杆样例错误');
    if (annotated) local.label = '副歌渐亮';
    const snapshots = snapshotMa2LightingBinding(document, bindingId, { consoleVersion: '3.3.4', baselineRevision: 'base', localRevision: 'local' });
    expect(snapshots.local.objects).toEqual(snapshots.base.objects);
    const confirmed = structuredClone(source);
    confirmed.document.tracks[0]!.clips[0]!.events[0] = { ...local, at: 500, level: 0.625, label: '主推杆' };
    const command = applyMa2ReadbackCommand('item', bindingId, document, confirmed);
    const saved = parseLinkProject(JSON.parse(JSON.stringify(command.execute(before))));
    const result = saved.rundown[0]!.lighting!;
    expect(result.tracks[0]!.clips[0]!.events[0]).toMatchObject({ at: 500, level: 0.625, label: annotated ? '副歌渐亮' : '主推杆' });
    expect(result.ma2Bindings![0]!.baselineTracks).toEqual(confirmed.document.tracks);
    expect(command.undo(before)).toEqual(before);
    const repeated = applyMa2ReadbackCommand('item', bindingId, result, confirmed).execute(saved);
    expect(repeated.rundown[0]!.lighting!.tracks).toEqual(result.tracks);
  });
  it('确认回读保留片段、节拍锁定和轨道样式，新增与删除一次应用并可撤销', () => {
    const before = importMa2TimecodeCommand('item', preview()).execute(project());
    const document = before.rundown[0]!.lighting!;
    const binding = document.ma2Bindings![0]!;
    const track = document.tracks[0]!; const clip = track.clips[0]!;
    document.tempos[0]!.bpm = 60;
    track.color = '#123456'; track.group = '本地分组'; track.solo = true;
    clip.name = '保留片段'; clip.timeLock = 'beat'; clip.start = 1; clip.duration = 4; clip.events[0]!.at = 1;
    clip.events.push({ ...clip.events[0]!, id: 'to-delete', at: 2 });
    const confirmed = preview();
    const incoming = confirmed.document.tracks[0]!.clips[0]!;
    incoming.events[0]!.at = 500;
    incoming.events.push({ ...incoming.events[0]!, id: 'new-event', at: 1000 });
    confirmed.mappings.push({ ...confirmed.mappings[0]!, eventId: 'new-event', path: 'Timecode:9901/Track:0/SubTrack:0/Event:2' });
    const command = applyMa2ReadbackCommand('item', binding.id, document, confirmed);
    const next = command.execute(before);
    const result = next.rundown[0]!.lighting!;
    expect(result.tracks[0]).toMatchObject({ color: '#123456', group: '本地分组', solo: true });
    const retained = result.tracks[0]!.clips[0]!;
    expect(retained).toMatchObject({ id: clip.id, name: '保留片段', timeLock: 'beat', start: 0.5, duration: 4.5 });
    expect(retained.events.map((event) => event.id)).toEqual(['ma-event']);
    expect(lightingEventTime(retained, retained.events[0]!, new LightingTempoMap(result.tempos))).toBe(500);
    expect(result.tracks[0]!.clips[1]!.events[0]!.id).toBe('new-event');
    expect(result.ma2Bindings![0]!.baselineTracks).toEqual(confirmed.document.tracks);
    expect(result.ma2Bindings![0]!.mappings).toEqual(confirmed.mappings);
    expect(command.undo(before)).toEqual(before);
    expect(parseLinkProject(JSON.parse(JSON.stringify(next)))).toEqual(next);
    expect(document.tracks[0]!.clips[0]!.events).toHaveLength(2);
  });
  it('本地轨道名称保留且不重命名控台执行器，未自定义名称跟随回读', () => {
    const before = importMa2TimecodeCommand('item', preview()).execute(project());
    const document = before.rundown[0]!.lighting!;
    const binding = document.ma2Bindings![0]!;
    const originalName = document.tracks[0]!.name;
    document.tracks[0]!.name = '副歌灯光';
    const snapshots = snapshotMa2LightingBinding(document, binding.id, { consoleVersion: '3.3.4', baselineRevision: 'base', localRevision: 'edit' });
    expect(snapshots.local.objects.find((object) => object.kind === 'track')?.properties.name).toBe(originalName);
    const remote = preview(); remote.document.tracks[0]!.name = '控台新执行器名称';
    const command = applyMa2ReadbackCommand('item', binding.id, document, remote);
    const saved = command.execute(before);
    const lighting = saved.rundown[0]!.lighting!;
    expect(lighting.tracks[0]!.name).toBe('副歌灯光');
    expect(lighting.ma2Bindings![0]!.baselineTracks[0]!.name).toBe('控台新执行器名称');
    expect(command.undo(before)).toEqual(before);
    expect(parseLinkProject(JSON.parse(JSON.stringify(saved)))).toEqual(saved);
    document.tracks[0]!.name = originalName;
    expect(applyMa2ReadbackCommand('item', binding.id, document, remote).execute(before).rundown[0]!.lighting!.tracks[0]!.name).toBe('控台新执行器名称');
  });
  it('同步期间修改灯光拒绝覆盖，其他节目资料修改仍可保留', () => {
    const before = importMa2TimecodeCommand('item', preview()).execute(project());
    const document = before.rundown[0]!.lighting!;
    const command = applyMa2ReadbackCommand('item', document.ma2Bindings![0]!.id, document, preview());
    const changed = structuredClone(before); changed.rundown[0]!.lighting!.tracks[0]!.clips[0]!.events[0]!.at = 1700;
    expect(() => command.execute(changed)).toThrow('未覆盖');
    expect(changed.rundown[0]!.lighting!.tracks[0]!.clips[0]!.events[0]!.at).toBe(1700);
    const renamed = structuredClone(before); renamed.rundown[0]!.title = '新节目名';
    expect(command.execute(renamed).rundown[0]!.title).toBe('新节目名');
  });
  it('真实回读 ID 变化后接入三方比较，分别改时间与名称可合并，同时间冲突可选择', () => {
    const read = preview();
    const imported = importMa2TimecodeCommand('item', read).execute(project());
    const document = imported.rundown[0]!.lighting!; const binding = document.ma2Bindings![0]!;
    document.tracks[0]!.clips[0]!.events[0]!.at = 1700;
    const remote = preview();
    const track = remote.document.tracks[0]!; track.id = 'remote-track';
    const clip = track.clips[0]!; clip.id = 'remote-clip';
    const event = clip.events[0]!; event.id = 'remote-event';
    if (event.kind !== 'ma2') throw new Error('测试事件类型错误');
    event.label = '控台重命名';
    remote.mappings[0] = { ...remote.mappings[0]!, trackId: track.id, clipId: clip.id, eventId: event.id };
    const metadata = { baselineVersion: '3.3.4', remoteVersion: '3.3.4', baselineRevision: 'base', localRevision: 'local', remoteRevision: 'remote' };
    const result = previewMa2BoundSync(document, binding.id, remote, new Map(), metadata);
    expect(result.conflicts).toEqual([]);
    expect(resolveMa2Sync(result, new Map()).objects.find((entry) => entry.id === 'ma-event')?.properties).toMatchObject({ time: '1700', name: '控台重命名' });
    event.at = 1800;
    const conflict = previewMa2BoundSync(document, binding.id, remote, new Map(), metadata);
    expect(conflict.conflicts).toHaveLength(1);
    expect(resolveMa2Sync(conflict, new Map([['ma-event', 'remote']])).objects.find((entry) => entry.id === 'ma-event')?.properties.time).toBe('1800');
    expect(() => previewMa2BoundSync(document, binding.id, remote, new Map(), { ...metadata, remoteVersion: 'other' })).toThrow('软件版本');
  });
  it('已保存绑定生成真实节目差异，基线时间不随本地节拍图改变', () => {
    const imported = importMa2TimecodeCommand('item', preview()).execute(project());
    const document = imported.rundown[0]!.lighting!;
    const binding = document.ma2Bindings![0]!;
    const clip = document.tracks[0]!.clips[0]!;
    const event = clip.events[0]!;
    clip.timeLock = 'beat'; clip.duration = 8; event.at = 2;
    document.tempos[0]!.bpm = 60;
    const snapshots = snapshotMa2LightingBinding(document, binding.id, { consoleVersion: '3.3.4', baselineRevision: 'base', localRevision: 'edit' });
    expect(snapshots.base.objects.find((object) => object.id === event.id)?.properties.time).toBe('1500');
    expect(snapshots.local.objects.find((object) => object.id === event.id)?.properties.time).toBe('2000');
    const remote = structuredClone(snapshots.base);
    remote.objects.find((object) => object.id === event.id)!.properties.name = '控台改名';
    const result = resolveMa2Sync(previewMa2Sync(snapshots.base, snapshots.local, remote), new Map());
    expect(result.objects.find((object) => object.id === event.id)?.properties).toMatchObject({ time: '2000', name: '控台改名', cue: '7.500', executor: '99.219' });
    clip.events = [];
    const deleted = snapshotMa2LightingBinding(document, binding.id, { consoleVersion: '3.3.4', baselineRevision: 'base', localRevision: 'delete' });
    expect(previewMa2Sync(deleted.base, deleted.local, remote).conflicts[0]?.local).toBeNull();
    expect(binding.baselineTracks[0]!.clips[0]!.events[0]!.at).toBe(1500);
  });
  it('一次命令加入轨道及独立基线，保存重开后映射保留，撤销恢复全部', () => {
    const original = project(); const read = preview(); const command = importMa2TimecodeCommand('item', read);
    const next = command.execute(original);
    expect(next.schemaVersion).toBe(2);
    expect(next.rundown[0]?.lighting?.tracks).toEqual(read.document.tracks);
    expect(next.rundown[0]?.lighting?.ma2Bindings?.[0]).toMatchObject({ timecode: 9902, sourceXml: read.sourceXml, mappings: read.mappings, baselineTracks: read.document.tracks });
    expect(parseLinkProject(JSON.parse(JSON.stringify(next)))).toEqual(next);
    expect(command.undo(original)).toEqual(original);
    expect(original.rundown[0]?.lighting).toBeUndefined();
    const event = next.rundown[0]?.lighting?.tracks[0]?.clips[0]?.events[0];
    if (!event) throw new Error('导入事件缺失');
    event.at = 1700;
    expect(next.rundown[0]?.lighting?.ma2Bindings?.[0]?.baselineTracks[0]?.clips[0]?.events[0]?.at).toBe(1500);
  });
  it('保留节目原有节拍、标记和灯光数据，禁止重复绑定', () => {
    const original = project(); const item = original.rundown[0]!;
    item.lighting = createLightingDocument(); item.lighting.tempos[0]!.bpm = 90;
    item.lighting.markers = [{ id: 'marker', name: '原标记', startMs: 1000, endMs: null }];
    const next = importMa2TimecodeCommand('item', preview()).execute(original);
    expect(next.rundown[0]?.lighting?.tempos).toEqual(item.lighting.tempos);
    expect(next.rundown[0]?.lighting?.markers).toEqual(item.lighting.markers);
    expect(next.rundown[0]?.notes).toBe('保留备注');
    expect(() => importMa2TimecodeCommand('item', preview()).execute(next)).toThrow('重复导入');
  });
  it('未转换事件、错误映射和已删除节目不能部分应用', () => {
    const read = preview(); read.unconverted.push({ path: 'event:3', reason: '未支持动作' });
    expect(importMa2TimecodeCommand('item', read).execute(project()).rundown[0]?.lighting?.ma2Bindings?.[0]?.nativeEvents).toEqual(read.unconverted);
    expect(() => importMa2TimecodeCommand('missing', preview()).execute(project())).toThrow('节目不存在');
    const invalid = preview(); invalid.mappings[0]!.eventId = 'missing';
    const original = project();
    expect(() => importMa2TimecodeCommand('item', invalid).execute(original)).toThrow('基线事件映射');
    expect(original.rundown[0]?.lighting).toBeUndefined();
  });
});

-- Add owned MIDI message fixtures, without playback or device output.
local p, filename = reaper.EnumProjects(-1, '')
assert(filename:match('reaper%-native%-loop%-6%.05%.rpp$') and reaper.CountTracks(p) == 13, 'Open the saved TBLINK loop fixture')
local index = reaper.CountTracks(p)
reaper.Undo_BeginBlock2(p)
reaper.InsertTrackAtIndex(index, false)
local track = reaper.GetTrack(p, index)
reaper.GetSetMediaTrackInfo_String(track, 'P_NAME', 'native-message-order', true)
reaper.SetMediaTrackInfo_Value(track, 'B_MUTE', 1)
local item = reaper.CreateNewMIDIItemInProj(track, 0, 6, true)
reaper.SetMediaItemInfo_Value(item, 'B_LOOPSRC', 0)
local take = reaper.GetActiveTake(item)
local ppq = reaper.MIDI_GetPPQPosFromProjQN(take, 1) - reaper.MIDI_GetPPQPosFromProjQN(take, 0)
assert(reaper.MIDI_InsertNote(take, false, false, 0, ppq, 0, 60, 100, false))
assert(reaper.MIDI_InsertTextSysexEvt(take, false, false, ppq / 2, -1, string.char(0x7f, 0x7f, 2, 1, 1, 0x31)))
assert(reaper.MIDI_InsertCC(take, false, false, ppq, 0xb0, 0, 7, 80))
assert(reaper.MIDI_InsertTextSysexEvt(take, true, false, ppq * 1.5, -1, string.char(0x7d, 1, 2, 3)))
assert(reaper.MIDI_InsertNote(take, false, true, ppq * 2, ppq * 2.5, 0, 65, 90, false))
assert(reaper.MIDI_InsertNote(take, true, false, ppq * 3, ppq * 3.5, 0, 67, 95, false))
assert(reaper.MIDI_InsertTextSysexEvt(take, false, true, ppq * 4, -1, string.char(0x7d, 9, 8)))
reaper.MIDI_Sort(take)
reaper.TrackList_AdjustWindows(false)
reaper.UpdateArrange()
reaper.Undo_EndBlock2(p, 'Create TBLINK native MIDI messages', -1)

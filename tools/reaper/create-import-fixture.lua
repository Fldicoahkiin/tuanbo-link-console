-- Run only in a newly created, empty test tab. No external MIDI or playback.
local p, filename = reaper.EnumProjects(-1, '')
assert(filename == '' and reaper.CountTracks(p) == 0 and reaper.CountTempoTimeSigMarkers(p) == 0, 'Use a new empty project tab')
reaper.Undo_BeginBlock2(p)
reaper.SetTempoTimeSigMarker(p, -1, 0, -1, -1, 120, 3, 4, false)
reaper.AddProjectMarker2(p, false, 1, 0, 'Point one', 1, 0)
reaper.AddProjectMarker2(p, true, 2, 5, 'Region one', 1, 0)
reaper.AddProjectMarker2(p, true, 3, 6, 'Region overlap', 2, 0)
reaper.InsertTrackAtIndex(0, false)
local track = reaper.GetTrack(p, 0)
reaper.GetSetMediaTrackInfo_String(track, 'P_NAME', 'TBLINK muted solo sample', true)
reaper.SetMediaTrackInfo_Value(track, 'B_MUTE', 1)
reaper.SetMediaTrackInfo_Value(track, 'I_SOLO', 2)
local item = reaper.CreateNewMIDIItemInProj(track, 0, 8, false)
local take = reaper.GetActiveTake(item)
reaper.MIDI_InsertNote(take, false, false, reaper.MIDI_GetPPQPosFromProjTime(take, 1), reaper.MIDI_GetPPQPosFromProjTime(take, 2), 0, 60, 100, false)
reaper.TrackList_AdjustWindows(false)
reaper.UpdateArrange()
reaper.Undo_EndBlock2(p, 'Create TBLINK import acceptance fixture', -1)

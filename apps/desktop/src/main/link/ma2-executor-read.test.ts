const input = { dataDirectory: 'C:/ma2', target: 9902, executor: '99.219' };
it.skipIf(!process.env.MA2_ONPC_NEW_BINDING_ACCEPTANCE)('空 Timecode 的新执行器关联完成打点、同步、控台修改回读与还原', async () => {
  const directory = process.env.MA2_ONPC_DATA_DIRECTORY ?? '';
  const bridge = new Ma2OnpcBridge(directory, () => false);
  const original = await bridge.request('READ', 9903);
  const report = inspectMa2TimecodeXml(original);
  expect(report.timecodes[0]?.attributes.name).toBe('TBLINK_CREATE_ACCEPTANCE_9903');
  expect(report.timecodes[0]?.tracks).toEqual([]);
  const preview = convertMa2Snapshot(await bridge.request('SNAPSHOT', 9903), 9903);
  const executor = await readMa2Executor(bridge, { dataDirectory: directory, target: 9903, executor: '99.219' });
  const initial = createLightingDocument();
  const lane = structuredClone(convertMa2Timecode(tcXml, [seqXml], 9902).document.tracks[0]!);
  lane.id = 'empty-lane'; lane.name = '节目灯光'; lane.clips = []; initial.tracks = [lane];
  const project = createEmptyLinkProject('从空节目验收');
  project.rundown.push({ id: 'item', title: '节目', enabled: true, notes: '', cues: [], visualLayers: [], referenceMediaClips: [] });
  const imported = importMa2TimecodeCommand('item', preview, initial).execute(project);
  const bindingId = imported.rundown[0]!.lighting!.ma2Bindings![0]!.id;
  const bound = bindMa2TrackCommand('item', bindingId, lane.id, executor.executor, executor.executorName, executor).execute(imported);
  const source = bound.rundown[0]!.lighting!; const track = source.tracks[0]!;
  track.clips.push({ id: 'program-clip', name: '节目', start: 0, duration: 4000, timeLock: 'time', muted: false, events: [] });
  for (const time of [500, 1500]) track.clips[0]!.events.push({ id: `cue-${time}`, kind: 'ma2', action: 'goto', at: time, ...nextLightingCue(source, track, time) });
  const service = new Ma2ApplyService(bridge, () => false);
  try {
    const result = await service.apply({ dataDirectory: directory, document: source, bindingId, readback: preview, choices: [], conflicts: [] });
    if (result.status !== 'verified') throw new Error(JSON.stringify(result));
    expect(result.confirmed.document.tracks[0]?.clips[0]?.events).toMatchObject([{ id: 'cue-500', at: 500, cue: '1.250' }, { id: 'cue-1500', at: 1500, cue: '7.500' }]);
    const accepted = applyMa2ReadbackCommand('item', bindingId, source, result.confirmed).execute(bound);
    const saved = parseLinkProject(JSON.parse(JSON.stringify(accepted))).rundown[0]!.lighting!;
    expect(saved.ma2Bindings![0]!.pendingTracks).toBeUndefined();
    expect(saved.tracks[0]?.name).toBe('节目灯光');
    expect(await service.apply({ dataDirectory: directory, document: saved, bindingId, readback: result.confirmed, choices: [], conflicts: [] })).toMatchObject({ status: 'verified', backupFile: null });
    const beforeEdit = await bridge.request('READ', 9903); const editReport = inspectMa2TimecodeXml(beforeEdit);
    const eventPath = editReport.timecodes[0]!.tracks[0]!.subtracks[0]!.events[1]!.path;
    await bridge.request('APPLY', 9903, beforeEdit, editMa2TimecodeEvents(beforeEdit, editReport.sha256, 9903, [{ kind: 'update', path: eventPath, rawTime: '60' }]));
    const remote = convertMa2Snapshot(await bridge.request('SNAPSHOT', 9903), 9903);
    const received = await service.apply({ dataDirectory: directory, document: saved, bindingId, readback: remote, choices: [], conflicts: [] });
    if (received.status !== 'verified') throw new Error(JSON.stringify(received));
    const reopened = applyMa2ReadbackCommand('item', bindingId, saved, received.confirmed).execute(accepted);
    expect(reopened.rundown[0]!.lighting!.tracks[0]!.clips[0]!.events).toMatchObject([{ id: 'cue-500', at: 500 }, { id: 'cue-1500', at: 2000 }]);
  } finally {
    const current = await bridge.request('READ', 9903);
    expect(inspectMa2TimecodeXml(current).timecodes[0]?.attributes.name).toBe('TBLINK_CREATE_ACCEPTANCE_9903');
    expect(inspectMa2TimecodeXml(await bridge.request('APPLY', 9903, current, original)).timecodes).toEqual(report.timecodes);
  }
}, 60000);
it('按执行器分配补读实际 Cue 列表并再次核对执行器', async () => {
  const bridge = { request: vi.fn().mockResolvedValueOnce(execXml).mockResolvedValueOnce(snapshot).mockResolvedValueOnce(execXml) };
  const result = await readMa2Executor(bridge, input);
  expect(result.cueCatalog[0]?.cues.map((cue) => cue.number)).toEqual(['1.250', '7.500']);
  const project = createEmptyLinkProject('执行器绑定');
  const document = createLightingDocument();
  const track = structuredClone(convertMa2Timecode(tcXml, [seqXml], 9902).document.tracks[0]!);
  track.clips = []; document.tracks = [track];
  document.ma2Bindings = [{ id: 'binding', timecode: 9902, name: '测试', readAt: result.readAt, sourceXml: tcXml, baselineTracks: [], mappings: [], cueCatalog: [{ sequence: 10, name: null, cues: [] }] }];
  project.rundown.push({ id: 'item', title: '节目', enabled: true, notes: '', cues: [], visualLayers: [], referenceMediaClips: [], lighting: document });
  project.schemaVersion = 2;
  const command = bindMa2TrackCommand('item', 'binding', track.id, result.executor, result.executorName, result);
  const bound = command.execute(project);
  const saved = parseLinkProject(JSON.parse(JSON.stringify(bound))).rundown[0]!.lighting!;
  expect(nextLightingCue(saved, saved.tracks[0]!, 0)).toMatchObject({ cue: '1.250', sequence: 9901, executor: '99.219' });
  expect(saved.ma2Bindings![0]!.cueCatalog).toHaveLength(2);
  expect(command.undo(project)).toEqual(project);
  expect(() => bindMa2TrackCommand('item', 'binding', track.id, '1.1', result.executorName, result).execute(project)).toThrow('不一致');
  expect(bridge.request.mock.calls).toEqual([['EXECUTOR', 99, '219'], ['SCOPE', 9902, '9901'], ['EXECUTOR', 99, '219']]);
});
it('读取过程中换序列或序列缺失时不返回可关联的预览', async () => {
  const changed = { request: vi.fn().mockResolvedValueOnce(execXml).mockResolvedValueOnce(snapshot).mockResolvedValueOnce(execXml.replace('<No>9901</No>', '<No>9902</No>')) };
  await expect(readMa2Executor(changed, input)).rejects.toThrow('分配或名称已改变');
  const missing = { request: vi.fn().mockResolvedValueOnce(execXml).mockResolvedValueOnce(tcXml) };
  await expect(readMa2Executor(missing, input)).rejects.toThrow('序列缺失');
  expect(missing.request).toHaveBeenCalledTimes(2);
});

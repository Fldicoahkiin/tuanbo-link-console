const execXml = (await readFile(new URL('./fixtures/ma2-executor-3.3.xml', import.meta.url), 'utf8')).replace('<Exec ', '<Exec tblink_executor_name="TBLINK_CUE_REFERENCE_ACCEPTANCE 99.219" ');

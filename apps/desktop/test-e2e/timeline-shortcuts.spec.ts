import { test, expect, _electron as electron } from '@playwright/test';
import { writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { join } from 'node:path';
import { createEmptyLinkProject, parseLinkProject } from '@tb/schema';

test('灯光打点按钮、M 与快捷键修改', async ({}, info) => {
  const wav = Buffer.alloc(44 + 48000 * 3 * 2);
  wav.write('RIFF'); wav.writeUInt32LE(wav.length - 8, 4); wav.write('WAVEfmt ', 8);
  wav.writeUInt32LE(16, 16); wav.writeUInt16LE(1, 20); wav.writeUInt16LE(1, 22);
  wav.writeUInt32LE(48000, 24); wav.writeUInt32LE(96000, 28); wav.writeUInt16LE(2, 32); wav.writeUInt16LE(16, 34);
  wav.write('data', 36); wav.writeUInt32LE(wav.length - 44, 40);
  for (let sample = 0; sample < 48000 * 3; sample++) wav.writeInt16LE(Math.round(Math.sin(sample * 0.06) * (5000 + 14000 * Math.exp(-(sample % 18000) / 6000))), 44 + sample * 2);
  await writeFile(info.outputPath('audio.wav'), wav);
  const project = parseLinkProject({ ...createEmptyLinkProject('快捷键测试'), playbackSource: 'p1', rundown: [{ id: 'song', title: '歌曲', cues: [], referenceAudio: { assetId: 'audio', relativePath: 'audio.wav', sha256: createHash('sha256').update(wav).digest('hex'), durationMs: 3000 } }] });
  const file = info.outputPath('show.tblink'); await writeFile(file, JSON.stringify(project));
  const app = await electron.launch({ args: [`--user-data-dir=${info.outputPath('profile')}`, join(process.cwd(), 'out/main/index.cjs')] });
  try {
    const page = await app.firstWindow(); await page.waitForLoadState('domcontentloaded');
    await app.evaluate(({ dialog }, path) => { dialog.showOpenDialog = () => Promise.resolve({ canceled: false, filePaths: [path] }); }, file);
    await page.getByRole('button', { name: '打开工程', exact: true }).click();
    await page.getByRole('navigation', { name: '主要工作区' }).getByRole('button', { name: '灯光工作台', exact: true }).click();
    await page.getByRole('button', { name: '打点', exact: true }).click();
    await expect(page.getByRole('button', { name: '音频 Cue 1', exact: true })).toHaveCount(1);
    await page.keyboard.press('m');
    await expect(page.getByRole('button', { name: '音频 Cue 2', exact: true })).toHaveCount(1);
    await page.getByRole('button', { name: '设置', exact: true }).click();
    await page.getByRole('navigation', { name: '设置子菜单' }).getByRole('button', { name: '播放', exact: true }).click();
    await page.getByRole('button', { name: '快捷键', exact: true }).click();
    const field = page.getByLabel('在播放头打点快捷键', { exact: true });
    await field.focus(); await page.keyboard.press('k'); await expect(field).toHaveValue('K');
    await page.getByRole('navigation', { name: '主要工作区' }).getByRole('button', { name: '灯光工作台', exact: true }).click();
    await page.locator('.reference-timeline').focus();
    await page.keyboard.press('m'); await expect(page.getByRole('button', { name: '音频 Cue 3', exact: true })).toHaveCount(0);
    await page.keyboard.press('k'); await expect(page.getByRole('button', { name: '音频 Cue 3', exact: true })).toHaveCount(1);
    await expect(page.getByLabel('滚轮移动速度', { exact: true })).toBeHidden();
    await page.locator('summary[aria-label="时间线设置"]').click();
    await expect(page.getByLabel('滚轮移动速度', { exact: true })).toHaveValue('0.1');
    await page.getByLabel('滚轮移动速度', { exact: true }).selectOption('0.5');
    await expect(page.getByLabel('滚轮移动速度', { exact: true })).toHaveValue('0.5');
    await page.keyboard.press('Escape');
    await expect(page.getByLabel('滚轮移动速度', { exact: true })).toBeHidden();
    await page.locator('.waveform-lane').first().click({ button: 'right', position: { x: 220, y: 70 } });
    const rightClickCue = page.getByRole('button', { name: '音频 Cue 4', exact: true });
    await expect(rightClickCue).toHaveCount(1);
    await expect(page.locator('.waveform-cue-point')).toHaveCount(4);
    await expect(rightClickCue).toHaveAttribute('title', /^Cue 4 · \d{2}:\d{2}:\d{2}:\d{2} ·/);
    await rightClickCue.click();
    await expect(rightClickCue).toHaveAttribute('aria-pressed', 'true');
    const cueTime = (await rightClickCue.getAttribute('title'))!.split(' · ')[1]!;
    await expect(page.getByLabel('当前 Cue 时间', { exact: true })).toHaveText(cueTime);
    await rightClickCue.click({ button: 'right' });
    await expect(page.getByRole('menu', { name: 'Cue 菜单' })).toBeVisible();
    await page.keyboard.press('Escape');
    const toolbar = page.locator('.timeline-toolbar');
    await rightClickCue.click();
    const cueLeft = await rightClickCue.evaluate(element => parseFloat(element.style.left));
    const playhead = page.locator('.timeline-playhead');
    const playheadLeft = await playhead.evaluate(element => element.style.left);
    await rightClickCue.hover(); await page.mouse.wheel(0, 100);
    await expect.poll(() => rightClickCue.evaluate(element => parseFloat(element.style.left))).toBeGreaterThan(cueLeft);
    expect(await playhead.evaluate(element => element.style.left)).toBe(playheadLeft);
    await rightClickCue.hover(); await page.mouse.wheel(0, -100);
    await expect.poll(() => rightClickCue.evaluate(element => parseFloat(element.style.left))).toBeCloseTo(cueLeft, 1);
    await page.getByRole('button', { name: '取消选择', exact: true }).click();
    await page.locator('.waveform-lane').first().hover(); await page.mouse.wheel(0, 100);
    await expect.poll(() => playhead.evaluate(element => parseFloat(element.style.left))).toBeGreaterThan(parseFloat(playheadLeft));
    expect(await toolbar.evaluate(element => element.scrollWidth <= element.clientWidth)).toBe(true);
    const toolbarBox = (await toolbar.boundingBox())!;
    const transportBox = (await page.locator('.timeline-transport').boundingBox())!;
    expect(Math.abs(toolbarBox.x + toolbarBox.width / 2 - transportBox.x - transportBox.width / 2)).toBeLessThan(1);
    await rightClickCue.click();
    await page.locator('.reference-timeline').screenshot({ path: info.outputPath('cue-editor.png') });
    await page.screenshot({ path: info.outputPath('shortcuts.png') });
  } finally { await app.close(); }
});

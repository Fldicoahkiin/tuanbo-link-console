import { writeFile, readFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { join } from 'node:path';
import { test, expect, _electron as electron } from '@playwright/test';
import { createEmptyLinkProject, createLightingDocument, createLightingUserLibrary, parseLinkProject } from '@tb/schema';

test('当前 Cue：分类加号与控台拖入合并同一个时间点，保存、撤销、重开', async ({}, info) => {
  const wav = Buffer.alloc(44 + 24000 * 10 * 2);
  wav.write('RIFF'); wav.writeUInt32LE(wav.length - 8, 4); wav.write('WAVEfmt ', 8); wav.writeUInt32LE(16, 16); wav.writeUInt16LE(1, 20); wav.writeUInt16LE(1, 22); wav.writeUInt32LE(24000, 24); wav.writeUInt32LE(48000, 28); wav.writeUInt16LE(2, 32); wav.writeUInt16LE(16, 34); wav.write('data', 36); wav.writeUInt32LE(wav.length - 44, 40);
  await writeFile(info.outputPath('reference.wav'), wav);
  const lighting = createLightingDocument(); lighting.outputMode = 'network';
  const library = createLightingUserLibrary();
  library.entries = [1,2,3].map(sequence => ({ id: `material-${sequence}`, name: `灯光素材 ${sequence}`, originalName: `灯光素材 ${sequence}`, revision: 1, kind: 'single', categoryIds: ['front:bright:3:front'], favorite: false, source: { endpoint: 'test', show: 'test', verified: true }, track: { id: `track-${sequence}`, name: '灯光', kind: 'ma2', color: '#68c9ed', group: '', muted: false, solo: false, locked: false, channel: 1, controller: 7, portProfileId: '', noteNames: {}, clips: [], cueStamp: { mode: 'fixed', sequence, cue: '1.000', executor: '' } } }));
  lighting.tracks = [{ ...library.entries[0]!.track, clips: [{ id: 'clip', name: '原编排', start: 0, duration: 10000, timeLock: 'time', muted: false, events: [{ id: 'original', kind: 'ma2', at: 2000, sequence: 1, executor: '', cue: '1.000', action: 'goto', label: '开场' }] }] }];
  const project = parseLinkProject({ ...createEmptyLinkProject('组合编辑验收'), schemaVersion: 2, ma2MaterialLibrary: { version: 2, source: 'test', userLibrary: library, library: { directory: { show: 'test', version: '3.7.0.5', generation: 'test', entries: [] }, readAt: new Date().toISOString(), fixtureUsage: [], errors: [], sequences: [1,2,3].map(sequence => ({ sequence, name: `序列 ${sequence}`, cues: [{ index: 0, number: '1.000', name: `灯光素材 ${sequence}` }] })) } }, rundown: [{ id: 'song', title: '组合编辑验收', enabled: true, notes: '', cues: [], visualLayers: [], referenceMediaClips: [], lighting, referenceAudio: { assetId: 'audio', relativePath: 'reference.wav', durationMs: 10000, sha256: createHash('sha256').update(wav).digest('hex') } }] });
  const file = info.outputPath('composition.tblink'); await writeFile(file, JSON.stringify(project));
  const app = await electron.launch({ args: [`--user-data-dir=${info.outputPath('profile')}`, join(process.cwd(), 'out/main/index.cjs')], env: { ...process.env, TBLINK_LOCAL_TEST_ACCESS: '1' } });
  const page = await app.firstWindow(); const errors: string[] = []; page.on('pageerror', error => errors.push(error.message));
  const events = async () => parseLinkProject(JSON.parse(await readFile(file, 'utf8'))).rundown[0]!.lighting!.tracks.flatMap(track => track.clips.flatMap(clip => clip.events));
  try {
    await page.setViewportSize({ width: 1360, height: 900 });
    await app.evaluate(({dialog}, path) => { dialog.showOpenDialog = () => Promise.resolve({canceled: false, filePaths: [path]}); }, file);
    await page.getByRole('button', {name: '打开工程', exact: true}).click();
    await page.getByRole('button', {name: '灯光工作台', exact: true}).click();
    await page.locator('.lighting-playback-settings > summary').click();
    await page.getByRole('checkbox', {name: '选中 Cue 实时播放', exact: true}).uncheck();
    await page.locator('.lighting-playback-settings > summary').click();
    const navigation = page.getByRole('navigation', {name: '灯光素材主菜单'});
    await expect(navigation.getByRole('button')).toHaveText(['控台素材', '面光', '轮廓', '效果']);
    await expect(page.getByRole('button', {name: '读取控台', exact: true})).toHaveCount(0);
    await expect(page.getByRole('button', {name: 'MA2 同步', exact: true})).toHaveCount(0);
    await page.locator('.waveform-cue-point').first().click();
    const composer = page.locator('.cue-composer');
    await expect(composer.getByLabel('Cue 名称', {exact: true})).toHaveValue('开场');
    await navigation.getByRole('button', {name: '面光', exact: true}).click();
    await page.getByRole('button', {name: '添加 灯光素材 2 到当前 Cue', exact: true}).click();
    await expect(composer.locator('.cue-ingredient')).toHaveCount(2);
    await expect.poll(async () => (await events()).length).toBe(2);
    await navigation.getByRole('button', {name: '控台素材', exact: true}).click();
    const source = page.getByRole('button', {name: '试听序列 3 灯光步 1.000', exact: true});
    await source.dragTo(composer.locator('.cue-drop-hint'));
    await expect(composer.locator('.cue-ingredient')).toHaveCount(3);
    await expect.poll(async () => (await events()).length).toBe(3);
    await composer.getByRole('button', {name: '移除素材 灯光素材 2', exact: true}).click();
    await page.getByRole('button', {name: '添加 灯光素材 2 到当前 Cue', exact: true}).click();
    await expect(composer.locator('.cue-ingredient')).toHaveCount(3);
    await composer.getByRole('button', {name: '移除素材 灯光素材 3', exact: true}).click();
    await navigation.getByRole('button', {name: '面光', exact: true}).click();
    await page.locator('.classification-cell').filter({has: page.getByText('灯光素材 3', {exact: true})}).getByRole('button').first().dragTo(composer.locator('.cue-drop-hint'));
    await expect(composer.locator('.cue-ingredient')).toHaveCount(3);
    await expect(composer.getByLabel('素材 1 序列', {exact: true})).not.toBeVisible();
    await composer.getByLabel('Cue 名称', {exact: true}).fill('开场组合');
    await composer.getByRole('button', {name: '保存 Cue', exact: true}).click();
    await expect.poll(async () => (await events()).length).toBe(3);
    await expect.poll(async () => (await events()).find(event => event.id === 'original')).toMatchObject({ at: 2000, label: '开场组合' });
    expect((await events()).map(event => event.effectGroupId)).toEqual(['original', 'original', 'original']);
    await expect(page.locator('.waveform-cue-point')).toHaveCount(1);
    await page.screenshot({path: info.outputPath('cue-composer.png')});
    await page.getByRole('button', {name: '撤销', exact: true}).click();
    await expect.poll(async () => (await events()).find(event => event.id === 'original')).toMatchObject({ label: '开场' });
    await page.getByRole('button', {name: '重做', exact: true}).click();
    await expect.poll(async () => (await events()).length).toBe(3);
    await page.locator('.waveform-cue-point').first().click();
    await page.setViewportSize({width: 1060, height: 720});
    await expect(composer.getByRole('button', {name: '保存 Cue', exact: true})).toBeVisible();
    expect(await composer.evaluate(element => element.scrollWidth <= element.clientWidth)).toBe(true);
    const status = (await page.locator('.topbar-connection-overview').boundingBox())!;
    const actions = (await page.locator('.lighting-topbar-actions').boundingBox())!;
    expect(status.x + status.width).toBeLessThanOrEqual(actions.x);
    await page.screenshot({path: info.outputPath('cue-composer-compact.png')});
    await page.reload(); await page.getByRole('button', {name: '灯光工作台', exact: true}).click();
    await page.locator('.waveform-cue-point').first().click();
    await expect(composer.locator('.cue-ingredient')).toHaveCount(3);
    await page.locator('.timeline-ruler').click({position: {x: 30, y: 10}});
    await expect(page.locator('.waveform-cue-point[aria-pressed=true]')).toHaveCount(0);
    // New Cue is a persisted empty location, even after editing a filled Cue.
    await page.getByRole('button', { name: '打点', exact: true }).click();
    await expect(composer.getByLabel('Cue 名称', { exact: true })).toHaveValue('');
    await expect(composer.locator('.cue-ingredient')).toHaveCount(0);
    await expect.poll(async () => (await events()).length).toBe(4);
    const empty = (await events()).find(event => event.kind === 'empty-cue')!;
    await expect(page.locator('.waveform-cue-point').first()).toHaveText('1');
    expect(empty).toMatchObject({ label: '' });
    expect(empty).not.toHaveProperty('sequence');
    await expect(page.locator('.waveform-cue-point')).toHaveCount(2);
    await navigation.getByRole('button', { name: '面光', exact: true }).click();
    await page.getByRole('button', { name: '添加 灯光素材 2 到当前 Cue', exact: true }).click();
    await expect.poll(async () => (await events()).find(event => event.id === empty.id)).toMatchObject({ kind: 'ma2', sequence: 2, at: empty.at });
    await expect(page.locator('.waveform-cue-point').first()).toHaveText('1');
    // Switch away without pressing Save, then come back: it must retain material 2.
    await composer.getByRole('button', { name: '关闭 Cue 编辑', exact: true }).click();
    await page.locator('.waveform-cue-point').last().click();
    await expect(composer.locator('.cue-ingredient')).toHaveCount(3);
    await page.locator('.waveform-cue-point').first().click();
    await expect(composer.locator('.cue-ingredient')).toHaveCount(1);
    await expect(composer.locator('.cue-ingredient-title strong')).toHaveText('灯光素材 2');
    await composer.getByRole('button', { name: '移除素材 灯光素材 2', exact: true }).click();
    await expect.poll(async () => (await events()).find(event => event.id === empty.id)?.kind).toBe('empty-cue');
    await page.locator('.waveform-cue-point').last().click();
    await page.locator('.waveform-cue-point').first().click();
    await expect(composer.locator('.cue-ingredient')).toHaveCount(0);
    await page.getByRole('button', { name: '添加 灯光素材 3 到当前 Cue', exact: true }).click();
    await expect.poll(async () => (await events()).find(event => event.id === empty.id)).toMatchObject({ kind: 'ma2', sequence: 3, at: empty.at });
    await page.reload(); await page.getByRole('button', {name: '灯光工作台', exact: true}).click();
    await page.locator('.waveform-cue-point').first().click();
    await expect(composer.locator('.cue-ingredient-title strong')).toHaveText('灯光素材 3');
    await composer.getByRole('button', { name: '移除素材 灯光素材 3', exact: true }).click();
    await page.getByRole('button', { name: '撤销', exact: true }).click();
    await page.locator('.waveform-cue-point').first().click();
    await expect(composer.locator('.cue-ingredient')).toHaveCount(1);
    await page.getByRole('button', { name: '重做', exact: true }).click();
    await page.locator('.waveform-cue-point').first().click();
    await expect(composer.locator('.cue-ingredient')).toHaveCount(0);
    await expect.poll(async () => (await events()).find(event => event.id === empty.id)?.kind).toBe('empty-cue');
    await page.reload(); await page.getByRole('button', {name: '灯光工作台', exact: true}).click();
    await page.locator('.waveform-cue-point').first().click();
    await expect(composer.locator('.cue-ingredient')).toHaveCount(0);
    await page.screenshot({path: info.outputPath('empty-cue-reopened.png')});
    expect(errors).toEqual([]);
  } finally { await page.evaluate(() => window.tbLink.setDocumentDirty(false)); await app.close(); }
});
